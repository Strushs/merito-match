-- ========================================
-- Trigger to prevent blocked users from messaging
-- ========================================
CREATE OR REPLACE FUNCTION prevent_blocked_messages()
RETURNS TRIGGER AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM blocked_users
    WHERE (blocker_id = NEW.sender_id AND blocked_id IN (
      SELECT user_a FROM matches WHERE id = NEW.match_id
      UNION
      SELECT user_b FROM matches WHERE id = NEW.match_id
    ))
    OR (blocked_id = NEW.sender_id AND blocker_id IN (
      SELECT user_a FROM matches WHERE id = NEW.match_id
      UNION
      SELECT user_b FROM matches WHERE id = NEW.match_id
    ))
  ) THEN
    RAISE EXCEPTION 'Cannot send message to blocked user';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER check_blocked_before_message
  BEFORE INSERT ON messages
  FOR EACH ROW
  EXECUTE FUNCTION prevent_blocked_messages();

